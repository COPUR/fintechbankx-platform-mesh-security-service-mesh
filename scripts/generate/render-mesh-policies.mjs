const nameLabel = (sa) => ({ 'app.kubernetes.io/name': sa });

function nsLookup(contract) {
  return Object.fromEntries(contract.namespaces.map((n) => [n.name, n]));
}

// ---------------------------------------------------------------- namespaces
function namespaces(contract) {
  return contract.namespaces.map((n) => {
    const labels = { 'fintechbankx.io/context': n.context };
    if (!n.injection || n.injection === 'enabled') labels['istio-injection'] = 'enabled';
    if (n.injection === 'disabled') labels['istio-injection'] = 'disabled';
    labels['fintechbankx.io/namespace-kind'] = n.kind;
    return { apiVersion: 'v1', kind: 'Namespace', metadata: { name: n.name, labels } };
  });
}

// -------------------------------------------------------- peer authentication
function peerAuthentications(contract) {
  const docs = [
    {
      apiVersion: SEC,
      kind: 'PeerAuthentication',
      metadata: { name: 'default', namespace: 'istio-system' },
      spec: { mtls: { mode: 'STRICT' } },
    },
  ];
  for (const n of injectedNamespaces(contract)) {
    docs.push({
      apiVersion: SEC,
      kind: 'PeerAuthentication',
      metadata: { name: 'default', namespace: n.name },
      spec: { mtls: { mode: 'STRICT' } },
    });
  }
  return docs;
}

// ----------------------------------------------------- request authentication
function jwtRule(contract, audiences, locations) {
  return {
    issuer: contract.identity.issuer,
    jwksUri: contract.identity.jwksUri,
    ...(audiences ? { audiences } : {}),
    ...(locations?.fromHeaders ? { fromHeaders: structuredClone(locations.fromHeaders) } : {}),
    ...(locations?.fromParams ? { fromParams: [...locations.fromParams] } : {}),
    forwardOriginalToken: true,
  };
}

// The gateway validates signature and issuer only; each workload additionally
// requires its own service id in `aud` (platform contract addendum). There is
// deliberately no namespace-wide rule without audiences, because Istio accepts
// a token that matches ANY applicable rule.
// Token locations are explicit and header-only for the gateway and every
// workload: with none Istio falls back to its defaults, which include the
// query parameter access_token (tokens in URLs leak into logs and caches).
// Workloads receive the token the gateway forwarded (forwardOriginalToken) or
// a service's own Authorization header, so they use the same list.
function headerTokenLocations(contract) {
  const l = contract.gateway.tokenLocations || {};
  if (!(l.fromHeaders || []).length || (l.fromParams || []).length || (l.fromCookies || []).length) {
    throw new Error('gateway.tokenLocations must list fromHeaders only (no fromParams, no fromCookies, no Istio defaults)');
  }
  return { fromHeaders: l.fromHeaders };
}

function requestAuthentications(contract) {
  const locations = headerTokenLocations(contract);
  const docs = [
    {
      apiVersion: SEC,
      kind: 'RequestAuthentication',
      metadata: { name: 'keycloak-jwt', namespace: contract.gateway.namespace },
      spec: { selector: { matchLabels: contract.gateway.selector }, jwtRules: [jwtRule(contract, null, locations)] },
    },
  ];
  for (const n of serviceNamespaces(contract)) {
    if (isException(contract, 'requestAuthentication', n.name)) continue;
    for (const w of n.workloads || []) {
      docs.push({
        apiVersion: SEC,
        kind: 'RequestAuthentication',
        metadata: { name: `keycloak-jwt-${w.serviceAccount}`, namespace: n.name },
        spec: {
          selector: { matchLabels: nameLabel(w.serviceAccount) },
          jwtRules: [jwtRule(contract, [w.serviceId], locations)],
        },
      });
    }
  }
  return docs;
}

// ------------------------------------------------------ authorization policies
function policyName(from) {
  return `allow-from-${from.ns}-${from.sa}`;
}

// meshConfig.pathNormalization MERGE_SLASHES collapses "//" before
// AuthorizationPolicy evaluation, but no mode removes a trailing slash, so
// every exclusion also excludes its trailing-slash and sub-path variants:
// "<path>/*" for a literal path ("*" suffix is a prefix match and covers
// "<path>/"), "<template>/" and "<template>/{**}" for a path template (a "*"
// segment is not valid inside a template).
export function withSubpathExclusions(notPaths) {
  const out = [];
  for (const p of notPaths) {
    const extra = p.endsWith('*') || p.endsWith('/') ? [] : p.includes('{') ? [`${p}/`, `${p}/{**}`] : [`${p}/*`];
    for (const x of [p, ...extra]) if (!out.includes(x)) out.push(x);
  }
  return out;
}

// Edge `when` conditions are rendered as the rule's Istio `when` list. A
// request.auth.* key is evaluated by the callee's sidecar, which only has
// request.auth when a RequestAuthentication selects that workload; without one
// the condition never matches and the edge silently denies everything.
function checkWhen(contract, e) {
  for (const c of e.when) {
    if (typeof c.key !== 'string' || !Array.isArray(c.values) || c.values.length === 0) {
      throw new Error(`edge ${e.from.ns}/${e.from.name} -> ${e.to.ns}/${e.to.name}: when entries need a key and non-empty values`);
    }
    if (!c.key.startsWith('request.auth.')) continue;
    const isService = serviceWorkloads(contract).some((w) => w.ns === e.to.ns && (w.name || w.serviceAccount) === e.to.name);
    if (!isService || isException(contract, 'requestAuthentication', e.to.ns)) {
      throw new Error(
        `edge ${e.from.ns}/${e.from.name} -> ${e.to.ns}/${e.to.name}: ${c.key} (request.auth) needs a RequestAuthentication on the callee, and ${e.to.ns}/${e.to.name} has none`,
      );
    }
  }
}

function authorizationPolicies(contract) {
  const docs = [];
  const gw = contract.gateway;

  for (const n of injectedNamespaces(contract)) {
    docs.push({
      apiVersion: SEC,
      kind: 'AuthorizationPolicy',
      metadata: {
        name: 'default-deny',
        namespace: n.name,
        annotations: { 'fintechbankx.io/purpose': 'Deny every request that no ALLOW policy matches.' },
      },
      spec: {},
    });
  }

  // Public entry: the gateway itself accepts traffic on its listeners.
  docs.push({
    apiVersion: SEC,
    kind: 'AuthorizationPolicy',
    metadata: { name: 'allow-public-listeners', namespace: gw.namespace },
    spec: {
      selector: { matchLabels: gw.selector },
      action: 'ALLOW',
      rules: [{ to: [{ operation: { ports: gw.containerPorts.map(String) } }] }],
    },
  });
  docs.push(requireJwt(gw.namespace, { matchLabels: gw.selector }));

  // Edge-derived ALLOW policies, one per (caller, callee).
  const grouped = new Map();
  for (const e of expandEdges(contract)) {
    if (!e.from.sidecar) throw new Error(`edge from ${e.from.ns}/${e.from.name}: workload has no sidecar, it cannot present a principal`);
    if (!e.to.sidecar) continue; // no sidecar on the callee: NetworkPolicy only
    const key = `${e.to.ns}/${e.to.name}|${e.from.ns}/${e.from.sa}`;
    if (!grouped.has(key)) grouped.set(key, { to: e.to, from: e.from, ops: [], evidence: [] });
    const g = grouped.get(key);
    const op = { ports: [String(e.port)] };
    if (e.methods) op.methods = e.methods;
    if (e.paths) op.paths = e.paths;
    if (e.notPaths) op.notPaths = withSubpathExclusions(e.notPaths);
    if (e.when) checkWhen(contract, e);
    g.ops.push({ op, when: e.when });
    if (e.evidence) g.evidence.push(e.evidence);
  }
  for (const g of [...grouped.values()].sort((a, b) =>
    `${a.to.ns}/${a.to.name}/${a.from.ns}/${a.from.sa}`.localeCompare(`${b.to.ns}/${b.to.name}/${b.from.ns}/${b.from.sa}`),
  )) {
    docs.push({
      apiVersion: SEC,
      kind: 'AuthorizationPolicy',
      metadata: {
        name: `${policyName(g.from)}-to-${g.to.name}`,
        namespace: g.to.ns,
        annotations: { 'fintechbankx.io/evidence': [...new Set(g.evidence)].join(' | ') },
      },
      spec: {
        selector: { matchLabels: g.to.selector },
        action: 'ALLOW',
        rules: g.ops.map(({ op, when }) => ({
          from: [{ source: { principals: [principal(contract, g.from.ns, g.from.sa)] } }],
          to: [{ operation: op }],
          ...(when ? { when: structuredClone(when) } : {}), // no YAML anchors in the output
        })),
      },
    });
  }

  // Health on the management port, and JWT on /api/** for service namespaces.
  for (const n of serviceNamespaces(contract)) {
    if ((n.workloads || []).length === 0) continue;
    docs.push({
      apiVersion: SEC,
      kind: 'AuthorizationPolicy',
      metadata: {
        name: 'allow-health-endpoints',
        namespace: n.name,
        annotations: {
          'fintechbankx.io/purpose':
            'Kubelet probes are rewritten by the sidecar agent (port 15020) and never reach this rule; ' +
            'it keeps /actuator/health on the management port reachable for mesh health checkers.',
        },
      },
      spec: {
        action: 'ALLOW',
        rules: [
          {
            to: [
              {
                operation: {
                  methods: ['GET'],
                  ports: [String(contract.ports.management)],
                  paths: ['/actuator/health', '/actuator/health/*'],
                },
              },
            ],
          },
        ],
      },
    });
  }
  for (const n of serviceNamespaces(contract)) {
    if (isException(contract, 'requestAuthentication', n.name)) continue;
    docs.push(requireJwt(n.name));
  }
  return docs;
}

function requireJwt(ns, selector) {
  return {
    apiVersion: SEC,
    kind: 'AuthorizationPolicy',
    metadata: {
      name: 'require-jwt-for-api',
      namespace: ns,
      annotations: { 'fintechbankx.io/purpose': 'Reject /api/** requests that carry no valid Keycloak JWT.' },
    },
    spec: {
      ...(selector ? { selector } : {}),
      action: 'DENY',
      rules: [
        {
          from: [{ source: { notRequestPrincipals: ['*'] } }],
          to: [{ operation: { paths: ['/api', '/api/*'] } }],
        },
      ],
    },
  };
}


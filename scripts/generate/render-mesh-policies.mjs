// ----------------------------------------------------- legacy (cut-over) backends
// Backends outside the mesh the gateway routes to during a strangler
// cut-over (contract gateway.legacyBackends). The gateway sends HTTP to port
// 80 of the ServiceEntry and originates TLS to 443 (DestinationRule SIMPLE,
// SNI and SAN = the host); both are exported to the gateway namespace only.
const LEGACY_PORT = 80;

function legacyBackends(contract) {
  const out = [];
  for (const [name, b] of Object.entries(contract.gateway.legacyBackends || {})) {
    if (typeof b.host !== 'string' || !/^[A-Za-z0-9_.-]+$/.test(b.host)) {
      throw new Error(`gateway.legacyBackends.${name}: host must be one literal host name (no wildcard)`);
    }
    out.push({ name, ...b });
  }
  return out;
}

function legacyBackendServiceEntries(contract) {
  return legacyBackends(contract).map((b) => ({
    apiVersion: NET,
    kind: 'ServiceEntry',
    metadata: { name: b.name, namespace: contract.gateway.namespace },
    spec: {
      exportTo: ['.'],
      location: 'MESH_EXTERNAL',
      hosts: [b.host],
      ports: [{ number: LEGACY_PORT, name: 'http-legacy', protocol: 'HTTP', targetPort: 443 }],
      resolution: 'DNS',
    },
  }));
}

function legacyBackendDestinationRules(contract) {
  return legacyBackends(contract).map((b) => ({
    apiVersion: NET,
    kind: 'DestinationRule',
    metadata: { name: b.name, namespace: contract.gateway.namespace },
    spec: {
      host: b.host,
      exportTo: ['.'],
      trafficPolicy: {
        connectionPool: { tcp: { connectTimeout: '1s' } },
        outlierDetection: { consecutive5xxErrors: 5, interval: '5s', baseEjectionTime: '30s', maxEjectionPercent: 50 },
        portLevelSettings: [{ port: { number: LEGACY_PORT }, tls: { mode: 'SIMPLE', sni: b.host, subjectAltNames: [b.host] } }],
      },
    },
  }));
}

// ------------------------------------------------------------------ sidecars
function sidecars(contract) {
  const docs = [
    {
      apiVersion: NET,
      kind: 'Sidecar',
      metadata: { name: 'default', namespace: 'istio-system' },
      spec: {
        egress: [{ hosts: ['./*', 'istio-system/*'] }],
        outboundTrafficPolicy: { mode: 'REGISTRY_ONLY' },
      },
    },
  ];
  const edges = expandEdges(contract);
  for (const n of injectedNamespaces(contract)) {
    if (n.name === contract.gateway.namespace) continue; // gateways ignore Sidecar
    const targets = new Set(['./*', 'istio-system/*']);
    for (const e of edges) {
      if (e.from.ns === n.name && e.to.ns !== n.name) targets.add(`${e.to.ns}/*`);
    }
    if (n.name === 'observability') {
      for (const s of serviceNamespaces(contract)) targets.add(`${s.name}/*`);
    }
    docs.push({
      apiVersion: NET,
      kind: 'Sidecar',
      metadata: { name: 'default', namespace: n.name },
      spec: {
        egress: [{ hosts: [...targets].sort() }],
        outboundTrafficPolicy: { mode: 'REGISTRY_ONLY' },
      },
    });
  }
  return docs;
}

// ------------------------------------------------------------ ingress routing
// TLS ends at this gateway, so it is the only trustworthy source of the
// public scheme, host and port. Every route overwrites the forwarded headers
// (a client-supplied value never reaches a service) and drops the RFC 7239
// Forwarded header and X-Forwarded-Prefix. DPoP-enforcing services build the
// proof's htu from these values (platform contract, DPoP section).
const forwardedHeaders = (host) => ({
  request: {
    set: { 'x-forwarded-proto': 'https', 'x-forwarded-host': host, 'x-forwarded-port': '443' },
    remove: ['forwarded', 'x-forwarded-prefix'],
  },
});

// Envoy local rate limit on the gateway for the anonymous open-data routes.
// The HTTP filter is inserted without a bucket (pass-through); each listed
// route (Envoy route name = VirtualService http route name) gets its own
// token bucket and returns 429 with x-fbx-rate-limited when it is empty.
// Per pod and route, shared by all clients; cluster-wide = x gateway replicas.
function effectiveLimit(rl) {
  if (rl.fillInterval !== '1s') throw new Error('anonymousRateLimit: effective-limit text assumes fillInterval 1s');
  const envs = Object.entries(rl.gatewayReplicas || {}).map(
    ([env, [min, max]]) => `${env} ${min}-${max} pods = ${rl.tokensPerFill * min}-${rl.tokensPerFill * max} req/s`,
  );
  return (
    `per gateway pod and route, shared by all clients: ${rl.tokensPerFill} req/s, burst ${rl.maxTokens}; ` +
    `cluster-wide per route = that x gateway replicas: ${envs.join(', ')}`
  );
}

function anonymousRateLimit(contract) {
  const rl = contract.gateway.anonymousRateLimit;
  if (!rl) return [];
  const known = new Set(serviceWorkloads(contract).filter((w) => w.apiPrefix).map((w) => w.serviceId));
  for (const r of rl.routes) if (!known.has(r)) throw new Error(`anonymousRateLimit: ${r} is not a gateway route`);
  const TYPE = 'type.googleapis.com/envoy.extensions.filters.http.local_ratelimit.v3.LocalRateLimit';
  const pct = (on) => ({ default_value: { numerator: on ? 100 : 0, denominator: 'HUNDRED' } });
  return [
    {
      apiVersion: 'networking.istio.io/v1alpha3',
      kind: 'EnvoyFilter',
      metadata: {
        name: 'anonymous-open-data-rate-limit',
        namespace: contract.gateway.namespace,
        annotations: { 'fintechbankx.io/effective-limit': effectiveLimit(rl) },
      },
      spec: {
        workloadSelector: { labels: contract.gateway.selector },
        configPatches: [
          {
            applyTo: 'HTTP_FILTER',
            match: { context: 'GATEWAY', listener: { filterChain: { filter: { name: 'envoy.filters.network.http_connection_manager', subFilter: { name: 'envoy.filters.http.router' } } } } },
            patch: {
              operation: 'INSERT_BEFORE',
              value: { name: 'envoy.filters.http.local_ratelimit', typed_config: { '@type': TYPE, stat_prefix: 'http_local_rate_limiter' } },
            },
          },
          ...rl.routes.map((route) => ({
            applyTo: 'HTTP_ROUTE',
            match: { context: 'GATEWAY', routeConfiguration: { vhost: { route: { name: route } } } },
            patch: {
              operation: 'MERGE',
              value: {
                typed_per_filter_config: {
                  'envoy.filters.http.local_ratelimit': {
                    '@type': TYPE,
                    stat_prefix: 'anonymous_open_data',
                    token_bucket: { max_tokens: rl.maxTokens, tokens_per_fill: rl.tokensPerFill, fill_interval: rl.fillInterval },
                    filter_enabled: { runtime_key: 'anonymous_open_data_enabled', ...pct(true) },
                    filter_enforced: { runtime_key: 'anonymous_open_data_enforced', ...pct(true) },
                    response_headers_to_add: [{ append_action: 'OVERWRITE_IF_EXISTS_OR_ADD', header: { key: 'x-fbx-rate-limited', value: 'true' } }],
                  },
                },
              },
            },
          })),
        ],
      },
    },
  ];
}

// Strangler cut-over routes (contract gateway.cutovers), rendered before
// every prefix route. Each rule becomes one route; its match entries are
// exact methods with anchored RE2 path regexes (Envoy safe_regex, full match
// on the path without query string). A cohort rule adds one match entry per
// cohort client on the gateway-validated claim (@request.auth.claims.<c>,
// Istio JWT claim routing, gateway only); with no client it is dropped,
// because a route without match entries matches every request.
const COHORT_CLIENT = /^[A-Za-z0-9][A-Za-z0-9._:-]*$/;
const NON_TPP_CLIENT = /^(svc-|fintechbankx-)/;

// A cohort route trusts the claims of whatever token the gateway extracted.
// Only Authorization headers may carry it: a query parameter (or cookie) token
// would let a URL select the cohort, and with no explicit location Istio
// falls back to its defaults, query access_token included.
function assertHeaderOnlyTokens(contract, name) {
  const l = contract.gateway.tokenLocations || {};
  if (!(l.fromHeaders || []).length || (l.fromParams || []).length || (l.fromCookies || []).length) {
    throw new Error(`cutover ${name}: a cohort rule needs gateway.tokenLocations with fromHeaders only (no fromParams, no fromCookies, no Istio defaults)`);
  }
}

function cutoverRoutes(contract) {
  const routes = [];
  const backends = Object.fromEntries(legacyBackends(contract).map((b) => [b.name, b]));
  for (const c of contract.gateway.cutovers || []) {
    const [ns, name] = c.target.split('/');
    const target = serviceWorkloads(contract).find((w) => w.ns === ns && (w.name || w.serviceAccount) === name);
    if (!target) throw new Error(`cutover ${c.name}: target ${c.target} is not a service workload`);
    const legacy = backends[c.legacy];
    if (!legacy) throw new Error(`cutover ${c.name}: legacy backend ${c.legacy} is not in gateway.legacyBackends`);
    const cohort = c.cohort || { clients: [] };
    for (const id of cohort.clients || []) {
      if (typeof id !== 'string' || !COHORT_CLIENT.test(id) || NON_TPP_CLIENT.test(id)) {
        throw new Error(`cutover ${c.name}: ${cohort.name} entry ${JSON.stringify(id)} must be one literal TPP client id (no wildcard, regex, service or channel client)`);
      }
    }
    if (!/^[a-z0-9_]+$/.test(cohort.claim || 'azp')) throw new Error(`cutover ${c.name}: ${cohort.name} claim must be a plain claim name`);
    const dest = {
      target: { host: `${target.serviceAccount}.${ns}.svc.cluster.local`, port: { number: contract.ports.http } },
      legacy: { host: legacy.host, port: { number: LEGACY_PORT } },
    };
    for (const r of c.rules) {
      if (!dest[r.to]) throw new Error(`cutover ${c.name} ${r.id}: to must be target or legacy`);
      const base = r.match.map((m) => {
        if (!/^[A-Z]+$/.test(m.method || '')) throw new Error(`cutover ${c.name} ${r.id}: every match needs one method`);
        if (!m.regex?.startsWith('^/') || !m.regex.endsWith('$') || /\.[*+]/.test(m.regex)) {
          throw new Error(`cutover ${c.name} ${r.id}: path regex must be anchored (^/...$) and contain no .* or .+`);
        }
        return { uri: { regex: m.regex }, method: { exact: m.method } };
      });
      let match = base;
      if (r.cohort) {
        if (!(cohort.clients || []).length) continue;
        assertHeaderOnlyTokens(contract, c.name);
        const header = `@request.auth.claims.${cohort.claim || 'azp'}`;
        match = base.flatMap((m) => cohort.clients.map((id) => ({ ...structuredClone(m), headers: { [header]: { exact: id } } })));
      }
      routes.push({
        name: `${c.name}-${r.id.toLowerCase()}`,
        match,
        route: [{ destination: dest[r.to] }],
        headers: forwardedHeaders('API_HOST'),
      });
    }
  }
  return routes;
}

function ingressRouting(contract) {
  const gw = contract.gateway;
  const routes = serviceWorkloads(contract)
    .filter((w) => w.apiPrefix)
    .map((w) => ({
      name: w.serviceId,
      match: [w.apiPrefix].flat().map((prefix) => ({ uri: { prefix } })),
      route: [{ destination: { host: `${w.serviceAccount}.${w.ns}.svc.cluster.local`, port: { number: contract.ports.http } } }],
      headers: forwardedHeaders('API_HOST'),
    }));
  return [
    {
      apiVersion: NET,
      kind: 'Gateway',
      metadata: { name: 'fintechbankx-public', namespace: gw.namespace },
      spec: {
        selector: gw.selector,
        servers: [
          {
            port: { number: 443, name: 'https', protocol: 'HTTPS' },
            hosts: ['API_HOST', 'IDENTITY_HOST'],
            tls: {
              mode: 'SIMPLE',
              credentialName: 'fintechbankx-ingress-tls',
              minProtocolVersion: 'TLSV1_2',
              cipherSuites: [
                'ECDHE-ECDSA-AES128-GCM-SHA256',
                'ECDHE-RSA-AES128-GCM-SHA256',
                'ECDHE-ECDSA-AES256-GCM-SHA384',
                'ECDHE-RSA-AES256-GCM-SHA384',
              ],
            },
          },
          {
            port: { number: 80, name: 'http', protocol: 'HTTP' },
            hosts: ['API_HOST', 'IDENTITY_HOST'],
            tls: { httpsRedirect: true },
          },
        ],
      },
    },
    {
      apiVersion: NET,
      kind: 'VirtualService',
      metadata: { name: 'fintechbankx-api', namespace: gw.namespace },
      spec: {
        hosts: ['API_HOST'],
        gateways: [`${gw.namespace}/fintechbankx-public`],
        http: [...cutoverRoutes(contract), ...routes],
      },
    },
    ...anonymousRateLimit(contract),
    {
      apiVersion: NET,
      kind: 'VirtualService',
      metadata: { name: 'fintechbankx-identity', namespace: gw.namespace },
      spec: {
        hosts: ['IDENTITY_HOST'],
        gateways: [`${gw.namespace}/fintechbankx-public`],
        http: [
          {
            name: 'keycloak-realm',
            match: [{ uri: { prefix: '/realms/fintechbankx/' } }, { uri: { prefix: '/resources/' } }],
            route: [{ destination: { host: 'keycloak.identity.svc.cluster.local', port: { number: 8080 } } }],
            headers: forwardedHeaders('IDENTITY_HOST'),
          },
        ],
      },
    },
  ];
}

// ---------------------------------------------------------- network policies
function np(ns, name, spec) {
  return { apiVersion: 'networking.k8s.io/v1', kind: 'NetworkPolicy', metadata: { name, namespace: ns }, spec };
}
const nsSel = (ns) => ({ namespaceSelector: { matchLabels: { 'kubernetes.io/metadata.name': ns } } });
const tcp = (ports) => ports.map((port) => ({ protocol: 'TCP', port: Number(port) }));

function peerSelector(contract, ref) {
  if (ref.ns === contract.gateway.namespace && ref.sa === contract.gateway.serviceAccount) {
    return { ...nsSel(ref.ns), podSelector: { matchLabels: contract.gateway.selector } };
  }
  return { ...nsSel(ref.ns), podSelector: { matchLabels: ref.selector } };
}

function networkPolicies(contract) {
  const docs = [];
  const lookup = nsLookup(contract);
  const edges = expandEdges(contract);
  const gw = contract.gateway;

  for (const n of contract.namespaces) {
    if (isException(contract, 'networkPolicyDefaultDeny', n.name)) continue;
    const ns = n.name;
    docs.push(np(ns, 'default-deny-all', { podSelector: {}, policyTypes: ['Ingress', 'Egress'] }));
    docs.push(
      np(ns, 'allow-egress-dns', {
        podSelector: {},
        policyTypes: ['Egress'],
        egress: [
          {
            to: [{ ...nsSel('kube-system'), podSelector: { matchLabels: { 'k8s-app': 'kube-dns' } } }],
            ports: [
              { protocol: 'UDP', port: 53 },
              { protocol: 'TCP', port: 53 },
            ],
          },
        ],
      }),
    );
    docs.push(
      np(ns, 'allow-egress-istiod', {
        podSelector: {},
        policyTypes: ['Egress'],
        egress: [{ to: [{ ...nsSel('istio-system'), podSelector: { matchLabels: { app: 'istiod' } } }], ports: tcp([15012]) }],
      }),
    );
    // Kubelet probes (rewritten to the agent on 15020) and sidecar readiness (15021) come from the nodes.
    docs.push(
      np(ns, 'allow-ingress-node-health', {
        podSelector: {},
        policyTypes: ['Ingress'],
        ingress: [{ from: [{ ipBlock: { cidr: PLACEHOLDER_CIDR } }], ports: tcp([15020, 15021]) }],
      }),
    );
    // Scraping: merged metrics (15020), Envoy stats (15090), app management port.
    if (ns !== 'observability') {
      docs.push(
        np(ns, 'allow-ingress-observability-scrape', {
          podSelector: {},
          policyTypes: ['Ingress'],
          ingress: [
            {
              from: [{ ...nsSel('observability'), podSelector: { matchLabels: nameLabel('prometheus') } }],
              ports: tcp([contract.ports.management, 15020, 15090]),
            },
          ],
        }),
      );
    }
    // AWS APIs (STS for IRSA, Secrets Manager, KMS) and the EKS API via VPC endpoints.
    if ((n.workloads || []).length > 0 || ns === gw.namespace) {
      docs.push(
        np(ns, 'allow-egress-vpc-https', {
          podSelector: {},
          policyTypes: ['Egress'],
          egress: [{ to: [{ ipBlock: { cidr: PLACEHOLDER_CIDR } }], ports: tcp([443]) }],
        }),
      );
    }

    // Datastores: egress only for the workloads that declare the store.
    const x = contract.externalDependencies;
    const storePorts = {
      'aurora-postgresql': ['allow-egress-aurora', [x['aurora-postgresql'].port]],
      msk: ['allow-egress-msk', x.msk.ports],
      documentdb: ['allow-egress-documentdb', [x.documentdb.port]],
      'elasticache-redis': ['allow-egress-redis', [x['elasticache-redis'].port]],
      // Public endpoints: the CIDR is fixed in the contract, hosts are limited by REGISTRY_ONLY.
      'aws-s3': ['allow-egress-aws-s3', [x['aws-s3'].port], x['aws-s3'].cidr],
      'alert-receivers': ['allow-egress-alert-receivers', [x['alert-receivers'].port], x['alert-receivers'].cidr],
    };
    for (const [store, [name, ports, cidr]] of Object.entries(storePorts)) {
      const users = (n.workloads || [])
        .filter((w) => (w.datastores || []).includes(store))
        .map((w) => {
          const sel = resolveWorkload(contract, ns, w.name || w.serviceAccount).selector;
          if (Object.keys(sel).length !== 1 || !sel['app.kubernetes.io/name']) {
            throw new Error(`${ns}/${w.serviceAccount}: datastore egress needs a selector on app.kubernetes.io/name only`);
          }
          return sel['app.kubernetes.io/name'];
        });
      if (!users.length) continue;
      docs.push(
        np(ns, name, {
          podSelector: { matchExpressions: [{ key: 'app.kubernetes.io/name', operator: 'In', values: [...new Set(users)].sort() }] },
          policyTypes: ['Egress'],
          egress: [{ to: [{ ipBlock: { cidr: cidr || PLACEHOLDER_CIDR } }], ports: tcp(ports) }],
        }),
      );
    }

    if (ns === gw.namespace) {
      docs.push(
        np(ns, 'allow-ingress-load-balancer', {
          podSelector: { matchLabels: gw.selector },
          policyTypes: ['Ingress'],
          ingress: [{ from: [{ ipBlock: { cidr: PLACEHOLDER_CIDR } }], ports: tcp([...gw.containerPorts, 15021]) }],
        }),
      );
    }

    // Edge-derived ingress (callee side) and egress (caller side).
    const inbound = new Map();
    const outbound = new Map();
    for (const e of edges) {
      if (e.to.ns === ns && e.from.ns !== ns) {
        const k = `${e.from.ns}`;
        if (!inbound.has(k)) inbound.set(k, { peers: new Map(), ports: new Set() });
        inbound.get(k).peers.set(`${e.from.ns}/${e.from.name}`, e.from);
        inbound.get(k).ports.add(e.port);
      }
      // Egress per calling workload and target namespace, one rule per
      // callee with that edge's ports: a pod reaches only what it calls.
      if (e.from.ns === ns && e.to.ns !== ns) {
        const k = `${e.from.name}|${e.to.ns}`;
        if (!outbound.has(k)) outbound.set(k, { from: e.from, toNs: e.to.ns, callees: new Map() });
        const callees = outbound.get(k).callees;
        if (!callees.has(e.to.name)) callees.set(e.to.name, { peer: e.to, ports: new Set() });
        callees.get(e.to.name).ports.add(e.port);
      }
      if (e.from.ns === ns && e.to.ns === ns) {
        inbound.set(`self:${e.from.name}:${e.to.name}:${e.port}`, { self: true, e });
      }
    }
    for (const [k, v] of [...inbound.entries()].sort()) {
      if (v.self) {
        const { e } = v;
        docs.push(
          np(ns, `allow-ingress-${e.from.name}-to-${e.to.name}-${e.port}`, {
            podSelector: { matchLabels: e.to.selector },
            policyTypes: ['Ingress'],
            ingress: [{ from: [{ podSelector: { matchLabels: e.from.selector } }], ports: tcp([e.port]) }],
          }),
        );
        docs.push(
          np(ns, `allow-egress-${e.from.name}-to-${e.to.name}-${e.port}`, {
            podSelector: { matchLabels: e.from.selector },
            policyTypes: ['Egress'],
            egress: [{ to: [{ podSelector: { matchLabels: e.to.selector } }], ports: tcp([e.port]) }],
          }),
        );
        continue;
      }
      docs.push(
        np(ns, `allow-ingress-from-${k}`, {
          podSelector: {},
          policyTypes: ['Ingress'],
          ingress: [
            {
              from: [...v.peers.values()].map((p) => peerSelector(contract, p)),
              ports: tcp([...v.ports].sort((a, b) => a - b)),
            },
          ],
        }),
      );
    }
    for (const [, v] of [...outbound.entries()].sort(([a], [b]) => a.localeCompare(b))) {
      docs.push(
        np(ns, `allow-egress-${v.from.name}-to-${v.toNs}`, {
          podSelector: { matchLabels: peerSelector(contract, v.from).podSelector.matchLabels },
          policyTypes: ['Egress'],
          egress: [...v.callees.keys()].sort().map((name) => {
            const c = v.callees.get(name);
            return { to: [peerSelector(contract, c.peer)], ports: tcp([...c.ports].sort((a, b) => a - b)) };
          }),
        }),
      );
    }
    // Prometheus scrapes every namespace except its own.
    if (ns === 'observability') {
      docs.push(
        np(ns, 'allow-egress-prometheus-scrape', {
          podSelector: { matchLabels: nameLabel('prometheus') },
          policyTypes: ['Egress'],
          egress: [
            {
              to: [{ namespaceSelector: {} }],
              ports: tcp([contract.ports.management, 9153, 15014, 15020, 15090]),
            },
          ],
        }),
      );
      // Node targets: node-exporter (hostNetwork 9100) and kubelet/cAdvisor (10250).
      docs.push(
        np(ns, 'allow-egress-prometheus-nodes', {
          podSelector: { matchLabels: nameLabel('prometheus') },
          policyTypes: ['Egress'],
          egress: [{ to: [{ ipBlock: { cidr: PLACEHOLDER_CIDR } }], ports: tcp([9100, 10250]) }],
        }),
      );
      // Workloads without a sidecar (exceptions.workloadInjection) that the
      // kube-apiserver calls: the prometheus-operator admission webhook.
      const operator = resolveWorkload(contract, ns, 'prometheus-operator');
      if (!operator.sidecar) {
        docs.push(
          np(ns, 'allow-ingress-operator-webhook', {
            podSelector: { matchLabels: operator.selector },
            policyTypes: ['Ingress'],
            ingress: [{ from: [{ ipBlock: { cidr: PLACEHOLDER_CIDR } }], ports: tcp([10250]) }],
          }),
        );
      }
    }
    // Platform namespaces run several cooperating components (Tempo, Loki, Grafana; Keycloak, LDAP).
    if (lookup[ns].kind === 'platform' && (n.workloads || []).length > 1) {
      docs.push(
        np(ns, 'allow-same-namespace', {
          podSelector: {},
          policyTypes: ['Ingress', 'Egress'],
          ingress: [{ from: [{ podSelector: {} }] }],
          egress: [{ to: [{ podSelector: {} }] }],
        }),
      );
    }
  }
  return docs;
}


// ------------------------------------------------ external secret admission
// ValidatingAdmissionPolicy (admissionregistration.k8s.io/v1, Kubernetes
// 1.30+) that keeps every ExternalSecret in a governed namespace on the
// service store and inside its own <env>/<slug>/ keys. Governed: every
// contract namespace (label fintechbankx.io/namespace-kind) except the
// platform-store namespaces. Namespaces without a scope entry get no slugs,
// so their ExternalSecrets are rejected (fail closed).
const cel = (s) => `'${s}'`;

function externalSecretAdmission(contract) {
  const sec = contract.secrets;
  const scopes = secretScopes(contract);
  const scopeMap =
    '{' + Object.entries(scopes).map(([ns, slugs]) => `${cel(ns)}: [${slugs.map(cel).join(', ')}]`).join(', ') + '}';
  const name = 'fintechbankx-externalsecret-scope';
  const policy = {
    apiVersion: 'admissionregistration.k8s.io/v1',
    kind: 'ValidatingAdmissionPolicy',
    metadata: {
      name,
      annotations: {
        'fintechbankx.io/purpose':
          `ExternalSecrets outside ${sec.platformStoreNamespaces.join(', ')} must use ClusterSecretStore ${sec.serviceStore} ` +
          'and read only <env>/<slug>/ keys; in service namespaces <slug> is the app.kubernetes.io/name label and must be ' +
          'a service account of that namespace.',
      },
    },
    spec: {
      failurePolicy: 'Fail',
      matchConstraints: {
        resourceRules: [
          { apiGroups: ['external-secrets.io'], apiVersions: ['*'], operations: ['CREATE', 'UPDATE'], resources: ['externalsecrets'] },
        ],
        namespaceSelector: {
          matchExpressions: [
            { key: 'fintechbankx.io/namespace-kind', operator: 'Exists' },
            { key: 'kubernetes.io/metadata.name', operator: 'NotIn', values: sec.platformStoreNamespaces },
          ],
        },
      },
      variables: [
        // Replaced per overlay (mesh-params ENVIRONMENT).
        { name: 'env', expression: cel('ENVIRONMENT') },
        { name: 'scopes', expression: scopeMap },
        {
          name: 'allowed',
          expression: 'request.namespace in variables.scopes ? variables.scopes[request.namespace] : []',
        },
        {
          name: 'serviceNamespace',
          expression:
            "has(namespaceObject.metadata.labels) && 'fintechbankx.io/namespace-kind' in namespaceObject.metadata.labels && " +
            "namespaceObject.metadata.labels['fintechbankx.io/namespace-kind'] == 'service'",
        },
        {
          name: 'slug',
          expression:
            "has(object.metadata.labels) && 'app.kubernetes.io/name' in object.metadata.labels ? " +
            "object.metadata.labels['app.kubernetes.io/name'] : ''",
        },
        {
          name: 'slugs',
          expression: 'variables.serviceNamespace ? variables.allowed.filter(s, s == variables.slug) : variables.allowed',
        },
        { name: 'prefixes', expression: "variables.slugs.map(s, variables.env + '/' + s + '/')" },
        {
          name: 'keys',
          expression:
            '(has(object.spec.data) ? object.spec.data.filter(d, has(d.remoteRef)).map(d, d.remoteRef.key) : []) + ' +
            '(has(object.spec.dataFrom) ? object.spec.dataFrom.filter(f, has(f.extract)).map(f, f.extract.key) : [])',
        },
      ],
      validations: [
        {
          expression: 'variables.slugs.size() > 0',
          messageExpression:
            "variables.allowed.size() == 0 ? 'namespace ' + request.namespace + ' has no secret scope in the mesh contract' : " +
            "'ExternalSecret in service namespace ' + request.namespace + " +
            "' must carry label app.kubernetes.io/name set to one of its service accounts: ' + variables.allowed.join(', ')",
          reason: 'Forbidden',
        },
        {
          expression:
            `has(object.spec.secretStoreRef) && object.spec.secretStoreRef.kind == 'ClusterSecretStore' && ` +
            `object.spec.secretStoreRef.name == ${cel(sec.serviceStore)}`,
          message: `secretStoreRef must be ClusterSecretStore ${sec.serviceStore}`,
          reason: 'Forbidden',
        },
        {
          expression: '!has(object.spec.data) || object.spec.data.all(d, !has(d.sourceRef) && has(d.remoteRef))',
          message: 'spec.data entries must use remoteRef and may not override the store (sourceRef)',
          reason: 'Forbidden',
        },
        {
          expression:
            '!has(object.spec.dataFrom) || object.spec.dataFrom.all(f, !has(f.sourceRef) && !has(f.find) && has(f.extract))',
          message: 'spec.dataFrom entries must use extract with an explicit key (no find, no sourceRef)',
          reason: 'Forbidden',
        },
        {
          expression: 'variables.slugs.size() == 0 || variables.keys.all(k, variables.prefixes.exists(p, k.startsWith(p)))',
          messageExpression:
            "'every remote key must start with ' + variables.prefixes.join(' or ') + '; got ' + " +
            'variables.keys.filter(k, !variables.prefixes.exists(p, k.startsWith(p))).join(\', \')',
          reason: 'Forbidden',
        },
        {
          // <env>/<slug>/db-import is the operator import credential
          // (terraform-modules operator-db-access); it never leaves Secrets
          // Manager for a cluster, not even for its own service.
          expression: "variables.keys.all(k, !k.endsWith('/db-import'))",
          messageExpression:
            "'remote keys ending in /db-import (operator import credential) are never synced into a cluster; got ' + " +
            "variables.keys.filter(k, k.endsWith('/db-import')).join(', ')",
          reason: 'Forbidden',
        },
      ],
    },
  };
  const binding = {
    apiVersion: 'admissionregistration.k8s.io/v1',
    kind: 'ValidatingAdmissionPolicyBinding',
    metadata: { name },
    spec: { policyName: name, validationActions: ['Deny'] },
  };
  return [policy, binding];
}

// --------------------------------------------------------------------- write
export function render(contract = loadContract()) {
  return {
    'namespaces.yaml': namespaces(contract),
    'peer-authentication.yaml': peerAuthentications(contract),
    'request-authentication.yaml': requestAuthentications(contract),
    'authorization-policies.yaml': authorizationPolicies(contract),
    'destination-rules.yaml': destinationRules(contract),
    'service-entries.yaml': serviceEntries(contract),
    'sidecars.yaml': sidecars(contract),
    'ingress-routing.yaml': ingressRouting(contract),
    'network-policies.yaml': networkPolicies(contract),
    'externalsecret-admission.yaml': externalSecretAdmission(contract),
  };
}

export function toText(docs) {
  return HEADER + docs.map((d) => '---\n' + YAML.stringify(d, { lineWidth: 0 })).join('');
}

function main() {
  const check = process.argv.includes('--check');
  const files = render();
  mkdirSync(outDir, { recursive: true });
  let drift = 0;
  for (const [file, docs] of Object.entries(files)) {
    const path = join(outDir, file);
    const text = toText(docs);
    if (check) {
      if (!existsSync(path) || readFileSync(path, 'utf8') !== text) {
        console.error(`drift: ${path} differs from the contract rendering`);
        drift++;
      }
    } else {
      writeFileSync(path, text);
      console.log(`wrote ${file} (${docs.length} documents)`);
    }
  }
  if (drift) process.exit(1);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
